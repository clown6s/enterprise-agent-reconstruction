"""Chat application ports. Implementations live outside this package."""
from typing import Protocol

from ..domain.models import (
    ChatMessage,
    IntentDecision,
    RetrievalItem,
    SopDefinition,
    SopExecutionState,
    SqlResult,
)


class LLM(Protocol):
    """A chat-capable language model with structured-output support."""

    def chat(self, messages: list[ChatMessage]) -> str: ...
    def close(self) -> None: ...


class DocumentRetriever(Protocol):
    def retrieve(self, query: str, *, top_k: int = 5,
                 filter: str = "") -> list[RetrievalItem]: ...
    def close(self) -> None: ...


class ConversationStore(Protocol):
    def get_or_create(self, conversation_id: str) -> None: ...
    def append(self, conversation_id: str, message: ChatMessage) -> None: ...
    def recent(self, conversation_id: str, limit: int = 10) -> list[ChatMessage]: ...


class IntentRouter(Protocol):
    def route(self, query: str, history: list[ChatMessage] | None = None) -> IntentDecision: ...


class SopStore(Protocol):
    def find(self, sop_id: str, version: str | None = None) -> SopDefinition | None: ...
    def search(self, query: str) -> list[SopDefinition]: ...
    def get_state(self, conversation_id: str) -> SopExecutionState | None: ...
    def save_state(self, conversation_id: str, state: SopExecutionState) -> None: ...


class SchemaCatalog(Protocol):
    def domains(self) -> list[str]: ...
    def describe(self, domain: str) -> str: ...
    def allowed_tables(self, domain: str) -> set[str]: ...
    def resolve_domain(self, query: str) -> str | None: ...


class ReadonlySqlExecutor(Protocol):
    def query(self, sql: str, *, timeout_s: float = 10.0,
              max_rows: int = 1000) -> SqlResult: ...
