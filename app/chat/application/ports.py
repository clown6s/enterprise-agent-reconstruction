"""Chat application ports. Implementations live outside this package."""
from typing import Protocol

from ..domain.models import (
    AuditEvent,
    ChatMessage,
    IntentDecision,
    RetrievalItem,
    SopDefinition,
    SopExecutionState,
    SqlResult,
    SessionState,
    ResolvedQuestion,
)


class LLM(Protocol):
    """A chat-capable language model with structured-output support."""

    def chat(self, messages: list[ChatMessage]) -> str: ...
    def close(self) -> None: ...


class DocumentRetriever(Protocol):
    def retrieve(self, query: str, *, top_k: int = 5,
                 filter: str = "") -> list[RetrievalItem]: ...
    def close(self) -> None: ...


class ConversationStore(Protocol):
    def get_or_create(self, conversation_id: str, *, context) -> None: ...
    def append(self, conversation_id: str, message: ChatMessage, *, context) -> None: ...
    def recent(self, conversation_id: str, limit: int = 10, *, context) -> list[ChatMessage]: ...


class IntentRouter(Protocol):
    def route(self, query: str, history: list[ChatMessage] | None = None) -> IntentDecision: ...


class IntentClassifier(Protocol):
    """语义意图分类；只返回分类决策，不可改权限或执行工具。"""
    def classify(self, query: str,
                 history: list[ChatMessage] | None = None) -> IntentDecision: ...


class SopStore(Protocol):
    def find(self, sop_id: str, version: str | None = None, *, context) -> SopDefinition | None: ...
    def search(self, query: str, *, context) -> list[SopDefinition]: ...
    def get_state(self, conversation_id: str, *, context) -> SopExecutionState | None: ...
    def save_state(self, conversation_id: str, state: SopExecutionState, *, context) -> None: ...


class SchemaRegistryPort(Protocol):
    def introspect(self, *, context, tables=None, include_columns=True) -> list[dict]: ...
    def register_domain(self, domain, *, context) -> None: ...
    def register_table(self, domain_id: str, table, *, context) -> None: ...
    def register_columns(self, domain_id: str, table_name: str, columns, *, context) -> None: ...
    def register_joins(self, domain_id: str, table_name: str, joins, *, context) -> None: ...
    def publish(self, domain_id: str, *, context, version: str | None = None,
                reason: str | None = None) -> dict | None: ...
    def list_domains(self, *, context) -> list[dict]: ...
    def list_tables(self, domain_id: str, *, context) -> list[dict]: ...
    def list_columns(self, domain_id: str, table_name: str, *, context) -> list[dict]: ...
    def list_joins(self, domain_id: str, *, context) -> list[dict]: ...


class SchemaCatalog(Protocol):
    def domains(self, *, context) -> list[str]: ...
    def describe(self, domain: str, *, context) -> str: ...
    def allowed_tables(self, domain: str, *, context) -> set[str]: ...
    def resolve_domain(self, query: str, *, context) -> str | None: ...


class ReadonlySqlExecutor(Protocol):
    def query(self, sql: str, *, timeout_s: float = 10.0,
              max_rows: int = 1000) -> SqlResult: ...


class RateLimiter(Protocol):
    def allow(self, key: str) -> bool: ...
    def close(self) -> None: ...


class UsageMeter(Protocol):
    def record(self, key: str, *, input_chars: int, output_chars: int,
               duration_ms: int) -> None: ...
    def close(self) -> None: ...


class HealthChecker(Protocol):
    def check(self) -> bool: ...


class TraceProvider(Protocol):
    def span(self, name: str, **attributes): ...


class AuditLogger(Protocol):
    """Append-only audit sink; failures must not change business results."""
    def record(self, event: AuditEvent) -> None: ...
    def close(self) -> None: ...


class SessionStateStore(Protocol):
    """Persistent structured multi-turn state per (tenant, conversation)."""
    def get(self, conversation_id: str, *, context) -> SessionState | None: ...
    def save(self, conversation_id: str, state: SessionState, *, context) -> None: ...
    def close(self) -> None: ...


class QuestionResolver(Protocol):
    """Resolve anaphora / elided follow-ups into a self-contained question."""
    def resolve(self, question: str, history: list[ChatMessage] | None,
                state: SessionState | None) -> ResolvedQuestion: ...


class ConversationUnderstanding(Protocol):
    """判断当前问题与历史的关系，不负责执行任何业务工具。"""
    def understand(self, question: str, history: list[ChatMessage] | None,
                   state: SessionState | None) -> ResolvedQuestion: ...
